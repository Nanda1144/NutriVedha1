import apiClient, { isMockEnabled } from './apiClient';
import { HealthScanResult, DietPlan, Recipe, ScanHistoryItem } from '../types';
import { MOCK_DIET_PLAN, MOCK_RECIPES } from './mockData';

let scanHistory: ScanHistoryItem[] = [
  {
    id: 'scan_001',
    date: '2026-10-14',
    condition: 'Forearm Epidermal Redness & Pitta Heat',
    dosha: 'Pitta',
    severity: 'Mild',
    summary: 'Localized heat erythema responding to topical Chandana and cooling aloe vera.',
  },
  {
    id: 'scan_002',
    date: '2026-08-22',
    condition: 'Dry Cuticular Dehydration & Joint Stiffness',
    dosha: 'Vata',
    severity: 'Moderate',
    summary: 'Elevated dry Vata signs, recommended internal warm sesame oil and Ashwagandha.',
  },
];

export const aiService = {
  async analyzeSymptoms(formData: { symptoms: string; imageFile?: File | null }): Promise<HealthScanResult> {
    if (isMockEnabled()) {
      await new Promise((r) => setTimeout(r, 1200));
      const s = formData.symptoms.toLowerCase();
      
      const isPitta = s.includes('burn') || s.includes('red') || s.includes('acid') || s.includes('heat') || s.includes('rash');
      const isKapha = s.includes('cold') || s.includes('mucus') || s.includes('heavy') || s.includes('sluggish');
      const detectedDosha = isPitta ? 'Pitta' : isKapha ? 'Kapha' : 'Vata';

      const result: HealthScanResult = {
        id: 'scan_' + Date.now(),
        symptoms: formData.symptoms,
        imageUrl: formData.imageFile ? URL.createObjectURL(formData.imageFile) : undefined,
        conditionAssessment: isPitta 
          ? 'Mild Pitta-dominant epidermal heat with localized reactive inflammation.'
          : isKapha 
          ? 'Sluggish Kapha accumulation with slow lymphatic stagnation.'
          : 'Elevated dry Vata bio-energy impacting tissue lubrication.',
        doshaImbalance: {
          primary: detectedDosha,
          severity: isPitta ? 'Mild' : 'Moderate',
          description: `Analysis shows symptomatic resonance with elevated ${detectedDosha} dosha.`,
        },
        recommendations: {
          herbs: isPitta 
            ? ['Amalaki (Amla)', 'Sandalwood (Chandana)', 'Guduchi'] 
            : isKapha 
            ? ['Trikatu', 'Ginger (Shunti)', 'Tulsi'] 
            : ['Ashwagandha', 'Bala', 'Shatavari'],
          lifestyleTips: [
            'Maintain regular sleep schedules aligned with circadian rhythms.',
            'Avoid overly pungent, excessively salty, or deep-fried foods during flare-ups.',
            'Practice gentle cooling pranayama (Shitali) twice daily.',
          ],
          dietAdjustments: [
            'Increase hydration with lukewarm water and herbal infusions.',
            'Incorporate pure A2 ghee in morning meals for cellular lubrication.',
          ],
        },
        urgencyLevel: 'Home Care / Routine',
        confidenceScore: 92.4,
        isFallback: false,
        safetyDisclaimer: 'This assessment is generated by an Ayurvedic clinical intelligence model for educational and preventive wellness guidance. It is not an official medical diagnostic report. Please consult a licensed physician or Vaidya for clinical conditions.',
        createdAt: new Date().toISOString(),
      };

      scanHistory.unshift({
        id: result.id,
        date: new Date().toISOString().split('T')[0],
        condition: result.conditionAssessment,
        dosha: result.doshaImbalance.primary,
        severity: result.doshaImbalance.severity,
        summary: result.recommendations.herbs.join(', '),
      });

      return result;
    }

    const payload = new FormData();
    payload.append('symptoms', formData.symptoms);
    if (formData.imageFile) {
      payload.append('image', formData.imageFile);
    }

    const res = await apiClient.post<{ data: HealthScanResult }>('/ai/scan', payload, {
      headers: { 'Content-Type': 'multipart/form-data' },
    });
    return res.data.data;
  },

  async getScanHistory(): Promise<ScanHistoryItem[]> {
    return scanHistory;
  },

  async generateDietPlan(preferences: any): Promise<DietPlan> {
    if (isMockEnabled()) {
      await new Promise((r) => setTimeout(r, 1000));
      return {
        ...MOCK_DIET_PLAN,
        id: 'diet_' + Date.now(),
        createdAt: new Date().toISOString(),
      };
    }
    const res = await apiClient.post<{ data: DietPlan }>('/ai/diet/generate', preferences);
    return res.data.data;
  },

  async getCurrentDietPlan(): Promise<DietPlan> {
    if (isMockEnabled()) {
      return MOCK_DIET_PLAN;
    }
    const res = await apiClient.get<{ data: DietPlan }>('/ai/diet/current');
    return res.data.data;
  },

  async getRecommendedRecipes(): Promise<Recipe[]> {
    if (isMockEnabled()) {
      return MOCK_RECIPES;
    }
    const res = await apiClient.get<{ data: Recipe[] }>('/ai/recipes/recommend');
    return res.data.data;
  },
};
